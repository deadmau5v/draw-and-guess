export const DEFAULT_AVATAR = '/assets/avatars/player-panda.png';
const presets = ['smile', 'corgi', 'anime', 'panda', 'burger', 'astronaut', 'fox', 'gamer', 'ghost', 'robot', 'witch'];
const allowed = new Set<string>([...presets.map(id => `/assets/avatars/player-${id}.png`), ...extraAvatars.map(avatar => avatar.src)]);
export function resolveAvatar(value: string | null | undefined): string {
  const extra = extraAvatars.find(avatar => avatar.id === value);
  const path = extra?.src ?? (value && presets.includes(value) ? `/assets/avatars/player-${value}.png` : value);
  return path && allowed.has(path) ? path : DEFAULT_AVATAR;
}
